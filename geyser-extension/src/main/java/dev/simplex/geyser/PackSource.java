package dev.simplex.geyser;

import org.geysermc.geyser.api.extension.Extension;
import org.geysermc.geyser.api.pack.PackCodec;
import org.geysermc.geyser.api.pack.ResourcePack;

import java.io.IOException;
import java.io.InputStream;
import java.io.Reader;
import java.io.StringReader;
import java.net.URI;
import java.net.http.HttpClient;
import java.net.http.HttpRequest;
import java.net.http.HttpResponse;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.StandardCopyOption;
import java.time.Duration;
import java.util.Properties;
import java.util.concurrent.Executors;
import java.util.concurrent.ScheduledExecutorService;
import java.util.concurrent.TimeUnit;

/**
 * Keeps track of the newest Bedrock pack generated by the Paper plugin. The pack is read either straight from
 * the plugin folder (Geyser on the same server) or downloaded from the plugin's built-in web server (proxy).
 */
final class PackSource {

    private final Extension extension;
    private final ExtensionConfig config;
    private final Translations translations;
    private final HttpClient http = HttpClient.newBuilder().connectTimeout(Duration.ofSeconds(5)).followRedirects(HttpClient.Redirect.NORMAL).build();
    private ScheduledExecutorService scheduler;

    private Path localFolder;
    private volatile ResourcePack currentPack;
    private volatile String currentSha = "";

    PackSource(Extension extension, ExtensionConfig config) {
        this.extension = extension;
        this.config = config;
        this.translations = new Translations(extension);
        this.localFolder = resolveLocalFolder();
    }

    Translations translations() { return translations; }

    ResourcePack currentPack() { return currentPack; }

    String describe() {
        return localFolder != null ? "local folder " + localFolder : "web server " + config.packUrl();
    }

    private Path resolveLocalFolder() {
        String configured = config.localFolder();
        if (configured != null && !configured.isBlank() && !configured.equalsIgnoreCase("auto")) {
            Path p = Path.of(configured);
            if (!p.isAbsolute()) p = extension.dataFolder().resolve(p).normalize();
            return p;
        }
        // dataFolder = <server>/plugins/Geyser-Spigot/extensions/simplexgeyser -> search the plugins folder.
        Path dir = extension.dataFolder().toAbsolutePath();
        for (int i = 0; i < 5 && dir != null; i++) {
            Path candidate = dir.resolve("SimplexImageToMap").resolve("generated").resolve("bedrock");
            if (Files.isDirectory(dir.resolve("SimplexImageToMap"))) return candidate;
            dir = dir.getParent();
        }
        return null;
    }

    void startPolling() {
        scheduler = Executors.newSingleThreadScheduledExecutor(r -> {
            Thread t = new Thread(r, "Simplex-PackPoller");
            t.setDaemon(true);
            return t;
        });
        scheduler.scheduleWithFixedDelay(this::refreshNow, config.pollSeconds(), config.pollSeconds(), TimeUnit.SECONDS);
    }

    void stop() {
        if (scheduler != null) scheduler.shutdownNow();
    }

    void scheduleLater(Runnable runnable, long seconds) {
        if (scheduler != null) scheduler.schedule(runnable, seconds, TimeUnit.SECONDS);
    }

    synchronized void refreshNow() {
        try {
            if (localFolder == null) localFolder = resolveLocalFolder();
            if (localFolder != null && Files.isRegularFile(localFolder.resolve("latest.properties"))) {
                refreshLocal();
            } else if (config.packUrl() != null && !config.packUrl().isBlank()) {
                refreshRemote();
            }
        } catch (Exception e) {
            extension.logger().debug("Simplex pack refresh failed: " + e.getMessage());
        }
    }

    private void refreshLocal() throws IOException {
        Properties latest = new Properties();
        try (Reader r = Files.newBufferedReader(localFolder.resolve("latest.properties"), StandardCharsets.UTF_8)) {
            latest.load(r);
        }
        String sha = latest.getProperty("sha1", "");
        if (sha.equals(currentSha)) return;
        Path file = localFolder.resolve(latest.getProperty("file", "SimplexPack.mcpack"));
        if (!Files.isRegularFile(file)) return;
        // Copy so the plugin can freely overwrite its output while Bedrock clients still download the old one.
        Path cached = cacheFile(sha);
        Files.copy(file, cached, StandardCopyOption.REPLACE_EXISTING);
        for (String locale : latest.getProperty("locales", "en_us").split(",")) {
            Path lang = localFolder.resolve("lang_" + locale.trim() + ".properties");
            if (Files.isRegularFile(lang)) translations.load(locale.trim(), Files.readString(lang, StandardCharsets.UTF_8));
        }
        swap(cached, sha);
    }

    private void refreshRemote() throws IOException, InterruptedException {
        String base = config.packUrl().endsWith("/") ? config.packUrl() : config.packUrl() + "/";
        HttpResponse<String> info = http.send(HttpRequest.newBuilder(URI.create(base + "latest.properties")).timeout(Duration.ofSeconds(10)).GET().build(),
                HttpResponse.BodyHandlers.ofString(StandardCharsets.UTF_8));
        if (info.statusCode() != 200) return;
        Properties latest = new Properties();
        latest.load(new StringReader(info.body()));
        String sha = latest.getProperty("sha1", "");
        if (sha.isEmpty() || sha.equals(currentSha)) return;
        Path cached = cacheFile(sha);
        HttpResponse<InputStream> pack = http.send(HttpRequest.newBuilder(URI.create(base + latest.getProperty("file"))).timeout(Duration.ofMinutes(2)).GET().build(),
                HttpResponse.BodyHandlers.ofInputStream());
        if (pack.statusCode() != 200) return;
        try (InputStream in = pack.body()) {
            Files.copy(in, cached, StandardCopyOption.REPLACE_EXISTING);
        }
        for (String locale : latest.getProperty("locales", "en_us").split(",")) {
            HttpResponse<String> lang = http.send(HttpRequest.newBuilder(URI.create(base + "lang_" + locale.trim() + ".properties")).timeout(Duration.ofSeconds(10)).GET().build(),
                    HttpResponse.BodyHandlers.ofString(StandardCharsets.UTF_8));
            if (lang.statusCode() == 200) translations.load(locale.trim(), lang.body());
        }
        swap(cached, sha);
    }

    private Path cacheFile(String sha) throws IOException {
        Path cache = extension.dataFolder().resolve("cache");
        Files.createDirectories(cache);
        return cache.resolve("SimplexPack-" + sha + ".mcpack");
    }

    private void swap(Path cached, String sha) {
        try {
            ResourcePack pack = ResourcePack.create(PackCodec.path(cached));
            String old = currentSha;
            currentPack = pack;
            currentSha = sha;
            extension.logger().info("Simplex Bedrock pack updated (" + sha.substring(0, Math.min(8, sha.length())) + ") – Bedrock players receive it on their next join.");
            cleanup(old);
        } catch (Exception e) {
            extension.logger().error("Invalid Simplex Bedrock pack: " + e.getMessage());
        }
    }

    private void cleanup(String keepSha) {
        Path cache = extension.dataFolder().resolve("cache");
        try (var files = Files.list(cache)) {
            files.filter(p -> {
                String n = p.getFileName().toString();
                return n.startsWith("SimplexPack-") && !n.contains(currentSha) && !n.contains(keepSha);
            }).forEach(p -> {
                try { Files.deleteIfExists(p); } catch (IOException ignored) { }
            });
        } catch (IOException ignored) {
        }
    }
}
