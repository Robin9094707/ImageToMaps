package dev.simplex.geyser;

import org.geysermc.geyser.api.extension.Extension;

import java.io.IOException;
import java.io.InputStream;
import java.io.Reader;
import java.io.Writer;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Properties;

/** Tiny properties based configuration – keeps the extension free of extra dependencies. */
public record ExtensionConfig(
        boolean customBlocks,
        String localFolder,
        String packUrl,
        int pollSeconds,
        float defaultBreakSeconds
) {

    private static final String DEFAULTS = """
            # Simplex Geyser extension configuration
            #
            # Where the Bedrock pack generated by the SimplexImageToMap Paper plugin is read from.
            # local-folder: folder that contains 'latest.properties' + the .mcpack (auto = detect the
            #               plugin folder next to Geyser when Geyser runs on the same Paper server)
            # pack-url:     used when the local folder can not be found (for example when Geyser runs on a
            #               Velocity/Bungee proxy). Point it to the plugin's built-in pack web server, e.g.
            #               http://127.0.0.1:8163/bedrock/
            local-folder=auto
            pack-url=http://127.0.0.1:8163/bedrock/
            # How often (seconds) the extension checks for a new pack. Players get the newest pack on (re)join.
            poll-seconds=15
            # Register Bedrock custom blocks (requires a Geyser restart to change).
            custom-blocks=true
            # Default break time (seconds) Bedrock clients predict for solid custom blocks.
            default-break-seconds=1.0
            """;

    public static ExtensionConfig load(Extension extension) {
        Path folder = extension.dataFolder();
        Path file = folder.resolve("config.properties");
        Properties props = new Properties();
        try {
            Files.createDirectories(folder);
            if (Files.notExists(file)) {
                try (Writer w = Files.newBufferedWriter(file, StandardCharsets.UTF_8)) {
                    w.write(DEFAULTS);
                }
            }
            try (Reader r = Files.newBufferedReader(file, StandardCharsets.UTF_8)) {
                props.load(r);
            }
        } catch (IOException e) {
            extension.logger().warning("Could not read config.properties, using defaults: " + e.getMessage());
            try (InputStream in = new java.io.ByteArrayInputStream(DEFAULTS.getBytes(StandardCharsets.UTF_8))) {
                props.load(in);
            } catch (IOException ignored) {
            }
        }
        return new ExtensionConfig(
                Boolean.parseBoolean(props.getProperty("custom-blocks", "true").trim()),
                props.getProperty("local-folder", "auto").trim(),
                props.getProperty("pack-url", "http://127.0.0.1:8163/bedrock/").trim(),
                parseInt(props.getProperty("poll-seconds", "15"), 15),
                parseFloat(props.getProperty("default-break-seconds", "1.0"), 1.0f)
        );
    }

    private static int parseInt(String s, int def) {
        try { return Math.max(3, Integer.parseInt(s.trim())); } catch (Exception e) { return def; }
    }

    private static float parseFloat(String s, float def) {
        try { return Float.parseFloat(s.trim()); } catch (Exception e) { return def; }
    }
}
